/**
 * Фото вкусов лежат в src/assets/flavors/ парами:
 *   <slug>.webp      — полноразмерное (окно «Подробные характеристики»)
 *   <slug>-sm.webp   — уменьшенное (карточка в каталоге)
 * Чтобы добавить новый вкус: положите обе картинки в эту папку и добавьте
 * запись в массив FLAVORS ниже — номер, подписи и спецификации подставятся сами.
 */
const flavorImages = import.meta.glob<string>('../assets/flavors/*.webp', {
  eager: true,
  import: 'default',
});

const flavorImage = (slug: string, small = false): string => {
  const key = `../assets/flavors/${slug}${small ? '-sm' : ''}.webp`;
  const url = flavorImages[key];
  if (!url) throw new Error(`Не найдено фото вкуса: ${key}`);
  return url;
};

